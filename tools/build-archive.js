// Builds archive/files.js: the list of original course materials in the Week_* / week_* folders
// (textbook chapters, assigned readings, lecture slides and links), for the Archive page.
// Run after adding or renaming files in a week folder:  node tools/build-archive.js
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");

// Readings metadata (author, title) from the drill, so the archive and the drills name them the same way
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "drill", "shared.js"), "utf8"), ctx);
const ARTICLES = ctx.window.BIO.ARTICLES;
const CHAPTERS = ["", "The Socially Charged Life of Language", "Gestures, Sign Languages, and Multimodality", "The Research Process in Linguistic Anthropology", "Language Acquisition and Socialization", "Language, Thought, and Culture", "Global Communities of Multilingual Language Users", "Literacy Practices", "Online Communities and Internet Linguistic Practices", "Performance, Performativity, and the Constitution of Communities", "Language and Gender", "Language, Race, and Ethnicity", "Language Endangerment and Revitalization", "Conclusion: Language, Power, and Agency"];
// Read & Learn chapter that covers each textbook chapter, for "Study it" links
const READ_OF = { 1: "social", 2: "gesture", 3: "methods", 4: "socialization", 5: "thought", 6: "multilingual", 7: "literacy", 8: "literacy", 9: "performance", 10: "performance", 11: "race", 12: "power", 13: "power" };
const READ_OF_ARTICLE = { RK: "social", GS: "methods", PA: "socialization", DG: "thought", WI: "multilingual", PH: "literacy", ZE: "race", HK: "race", SD: "race", PE: "power", AL: "power" };

const url = (...parts) => parts.map(encodeURIComponent).join("/");
const weekOf = d => +(d.match(/(\d+)$/) || [0, 0])[1];
const dirs = fs.readdirSync(root).filter(d => /^we+k_\d+$/i.test(d) && fs.statSync(path.join(root, d)).isDirectory()).sort((a, b) => weekOf(a) - weekOf(b));

function linkInfo(u) {
  if (/youtu\.?be/.test(u)) return { type: "video", title: "Video (YouTube)" };
  if (/criterion\.com/.test(u)) { const slug = (u.split("/").pop() || "").replace(/^\d+-/, "").replace(/-/g, " "); return { type: "link", title: "Criterion essay: " + slug.replace(/\b\w/g, c => c.toUpperCase()).replace(/(\w) S (?=\w)/g, "$1's ").replace(/ (Of|And|A)\b/g, m => m.toLowerCase()).replace(/ The Gift/, ": The Gift") } }
  if (/tandfonline\.com/.test(u)) return { type: "link", title: "Journal article (Taylor & Francis)" };
  return { type: "link", title: u.replace(/^https?:\/\//, "").split("/")[0] };
}

const seenReadings = {};
const weeks = dirs.map(d => {
  const week = weekOf(d), items = [];
  for (const f of fs.readdirSync(path.join(root, d)).sort()) {
    const p = url(d, f), size = fs.statSync(path.join(root, d, f)).size;
    let m;
    if (/\.txt$/i.test(f)) {
      const urls = fs.readFileSync(path.join(root, d, f), "utf8").split(/\s+/).filter(Boolean).map(u => /^https?:/.test(u) ? u : "https://" + u);
      urls.forEach(u => items.push({ kind: "link", href: u, ...linkInfo(u) }));
    } else if ((m = f.match(/^(\d+) .+\.pdf$/i))) {
      const n = +m[1];
      items.push({ kind: "textbook", type: "pdf", href: p, size, title: `Ch ${n} · ${CHAPTERS[n] || f.replace(/\.pdf$/i, "")}`, sub: "Ahearn, Living Language (3rd ed.)", read: READ_OF[n] });
    } else if (/\.pdf$/i.test(f)) {
      const a = ARTICLES.find(a => f.toLowerCase().startsWith(a.author.split(/[ &]/)[0].toLowerCase())) || (/^chap 3 methodology/i.test(f) ? ARTICLES.find(a => a.key === "GS") : null);
      const again = a && seenReadings[a.key];
      if (a) seenReadings[a.key] = seenReadings[a.key] || week;
      items.push({ kind: "reading", type: "pdf", href: p, size, title: a ? `${a.author}: ${a.title}` : f.replace(/\.pdf$/i, ""), sub: again ? `Assigned reading · same as week ${again}` : "Assigned reading", read: a ? READ_OF_ARTICLE[a.key] : null, drill: !!a });
    } else if (/\.zip$/i.test(f)) {
      items.push({ kind: "slides", type: "zip", href: p, size, title: "Lecture slides: Language Acquisition and Socialization", sub: "PowerPoint, in a .zip from Brightspace", read: "socialization" });
    } else {
      items.push({ kind: "file", type: (f.split(".").pop() || "").toLowerCase(), href: p, size, title: f });
    }
  }
  const order = { textbook: 0, reading: 1, slides: 2, file: 3, link: 4 };
  items.sort((x, y) => order[x.kind] - order[y.kind]);
  return { week, folder: d, items };
});

fs.mkdirSync(path.join(root, "archive"), { recursive: true });
fs.writeFileSync(path.join(root, "archive", "files.js"), "// Generated by tools/build-archive.js from the week folders. Do not edit by hand.\nwindow.ARCHIVE = " + JSON.stringify(weeks, null, 1) + ";\n");
const n = k => weeks.reduce((s, w) => s + w.items.filter(i => i.kind === k).length, 0);
console.log(`archive: ${weeks.length} weeks · ${n("textbook")} chapters · ${n("reading")} readings · ${n("slides")} slides · ${n("link")} links`);
